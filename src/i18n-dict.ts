// The translations, English text as the key. No imports: the panel (through src/i18n.ts) and the
// worker (its notification) both read them. resolveLanguage picks the language.

export type UiLanguage = 'en' | 'vi' | 'zh'

export function resolveLanguage(setting: string, locale: string): UiLanguage {
  if (setting === 'en' || setting === 'vi' || setting === 'zh') return setting
  const lower = locale.toLowerCase()
  if (lower.startsWith('vi')) return 'vi'
  if (lower.startsWith('zh')) return 'zh'
  return 'en'
}

/** Fills a template: the translation of `text` (English when there is none), with {name} params. */
export function translate(lang: UiLanguage, text: string, params?: Record<string, string | number>): string {
  const dict: Record<string, string> = lang === 'vi' ? VI : lang === 'zh' ? ZH : {}
  const template = dict[text] ?? text
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in params ? String(params[key]) : match))
}

